def field_help(model, field_name: str | None) -> str:
    """Пояснение для поля модели: сначала своё, потом общее для одноимённых полей."""
    if model is None or not field_name:
        return ""
    label = model._meta.label_lower
    return FIELD_HELP.get(label, {}).get(field_name) or COMMON.get(field_name, "")
